import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`optional whole-list properties in ${english ? 'English desktop playground' : 'Russian mobile homepage'}`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.setViewportSize({ width: english ? 1280 : 390, height: 900 });
  await page.goto(english ? '/playground' : '/ru/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const panel = page.locator('.lab-list-properties');
  await panel.locator('summary').click();
  await panel.getByRole('button', { name: t('Загрузить свойства списка', 'Load list properties sample'), exact: true }).click();
  const outer = content.locator('[title="List properties sample"]');
  const nested = content.locator('[title="List properties nested"]');
  const originalText = await content.textContent();
  const selectedText = await page.evaluate(() => document.getSelection()!.toString());
  const status = panel.getByRole('status');
  const toolbar = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true });
  const undo = toolbar.locator('[data-mw-ui-action="undo"]');
  const redo = toolbar.locator('[data-mw-ui-action="redo"]');
  await expect(outer).toHaveAttribute('reversed', '');
  await expect(status).toContainText('start: 3; reversed: true');
  await panel.getByRole('spinbutton', { name: t('Начальное число списка', 'List starting number'), exact: true }).fill('7');
  await panel.getByRole('button', { name: t('Применить начало', 'Apply start'), exact: true }).click();
  await expect(outer).toHaveAttribute('start', '7');
  expect(await page.evaluate(() => document.getSelection()!.toString())).toBe(selectedText);
  const reversed = panel.getByRole('checkbox', { name: t('Обратная нумерация', 'Reversed numbering'), exact: true });
  await reversed.uncheck();
  await panel.getByRole('button', { name: t('Применить направление нумерации', 'Apply numbering direction'), exact: true }).click();
  await expect(outer).not.toHaveAttribute('reversed');
  await undo.click();
  await expect(outer).toHaveAttribute('reversed', '');
  await redo.click();
  await expect(outer).not.toHaveAttribute('reversed');
  const marker = panel.getByRole('combobox', { name: t('Маркер списка', 'List marker'), exact: true });
  await marker.selectOption('upper-roman');
  await panel.getByRole('button', { name: t('Применить маркер', 'Apply marker'), exact: true }).click();
  await expect(status).toContainText('marker: upper-roman');
  expect(await outer.evaluate((node) => node.style.listStyleType)).toBe('upper-roman');
  await expect(outer.locator(':scope > li')).toHaveCount(2);
  await expect(outer.locator('strong')).toHaveText('one');
  await expect(outer.locator('em')).toHaveText('Beta');
  await expect(nested).not.toHaveAttribute('style');
  expect(await content.textContent()).toBe(originalText);
  // Undo/Redo can rebuild snapshots; inspect fresh nodes for the next property edit.
  const itemBeforeReset = await outer.locator(':scope > li').first().elementHandle();
  const branchBeforeReset = await nested.elementHandle();
  await panel.getByRole('button', { name: t('Сбросить свойства', 'Reset properties'), exact: true }).click();
  await expect(outer).not.toHaveAttribute('start');
  await expect(outer).not.toHaveAttribute('reversed');
  expect(await outer.evaluate((node) => node.style.listStyleType)).toBe('');
  await expect(status).toContainText(`start: ${t('Не задан', 'Not set')}`);
  expect(await itemBeforeReset!.evaluate((node) => node.isConnected)).toBe(true);
  expect(await branchBeforeReset!.evaluate((node) => node.isConnected)).toBe(true);
  await undo.click();
  await expect(outer).toHaveAttribute('start', '7');
  expect(await outer.evaluate((node) => node.style.listStyleType)).toBe('upper-roman');
  await redo.click();
  await expect(outer).not.toHaveAttribute('start');
  if (english) {
    await nested.locator('li').evaluate((node) => {
      const text = node.firstChild!;
      node.closest<HTMLElement>('.mw-content')!.focus();
      document.getSelection()!.setBaseAndExtent(text, 1, text, 1);
      document.dispatchEvent(new Event('selectionchange'));
    });
    await marker.selectOption('square');
    await panel.getByRole('button', { name: 'Apply marker', exact: true }).click();
    expect(await nested.evaluate((node) => node.style.listStyleType)).toBe('square');
    expect(await outer.evaluate((node) => node.style.listStyleType)).toBe('');
    await expect(status).toContainText('Kind: bullet');
    await page.keyboard.type('X');
    await expect(nested).toHaveText('NXested branch');
    await undo.click();
    await expect(nested).toHaveText('Nested branch');
    expect(await nested.evaluate((node) => node.style.listStyleType)).toBe('square');
  }
  await page.getByRole('button', { name: t('Только чтение', 'Read only'), exact: true }).click();
  await expect(panel.getByRole('button', { name: t('Применить маркер', 'Apply marker'), exact: true })).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
});
