import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`mixed link actions change only selected portions in ${english ? 'English' : 'Russian'}`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const lab = page.locator('.lab-contextual-link');
  await lab.locator('summary').click();
  const load = lab.getByRole('button', { name: t('Загрузить выделение нескольких ссылок', 'Load multiple-link selection'), exact: true });
  await load.click();
  const block = content.locator('[title="Mixed contextual link sample"]');
  const panel = page.locator('.mw-contextual-link');
  const text = await block.textContent();
  await expect(panel).toBeVisible();
  await expect(page.locator('.mw-contextual-toolbar')).toBeHidden();
  await expect(panel.locator('[data-mw-link-action="open"]')).toBeHidden();
  await expect(panel.locator('[data-mw-link-action="open"]')).not.toHaveAttribute('href');
  await panel.getByRole('button', { name: t('Задать ссылку выделению', 'Set link for selection'), exact: true }).click();
  const href = panel.getByLabel(t('Адрес ссылки', 'Link URL'), { exact: true });
  await expect(href).toHaveValue('');
  await expect(panel.getByLabel(t('Заголовок ссылки', 'Link title'), { exact: true })).toHaveValue('');
  await href.fill('https://example.com/shared');
  await panel.getByLabel(t('Заголовок ссылки', 'Link title'), { exact: true }).fill('Shared');
  await href.press('Enter');
  await expect(block.locator('a[href="https://example.com/shared"]')).toHaveText('pha + plain + Be');
  await expect(block.locator('a[href="https://example.com/first"]')).toHaveText('Al');
  await expect(block.locator('a[href="https://example.com/first"]')).toHaveAttribute('title', 'First');
  await expect(block.locator('a[href="https://example.com/second"]')).toHaveText('ta');
  await expect(block.locator('a[href="https://example.com/second"]')).toHaveAttribute('title', 'Second');
  expect(await block.textContent()).toBe(text);
  const toolbar = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true });
  await toolbar.locator('[data-mw-ui-action="undo"]').click();
  await expect(block.locator('a')).toHaveCount(2);
  await expect(block.locator('a').first()).toHaveText('Alpha');
  await expect(toolbar.locator('[data-mw-ui-action="undo"]')).toBeDisabled();
  await load.click();
  await expect(panel).toBeVisible();
  await panel.getByRole('button', { name: t('Убрать ссылки из выделения', 'Remove links from selection'), exact: true }).click();
  await expect(block.locator('a')).toHaveCount(2);
  await expect(block.locator('a').first()).toHaveText('Al');
  await expect(block.locator('a').last()).toHaveText('ta');
  expect((await block.locator('strong').allTextContents()).join('')).toBe('Alpha');
  expect((await block.locator('em').allTextContents()).join('')).toBe('Beta');
  expect(await block.textContent()).toBe(text);
  await load.click();
  await page.getByRole('button', { name: t('Только чтение', 'Read only'), exact: true }).click();
  await expect(panel.locator('button:enabled:visible')).toHaveCount(0);
  await expect(panel.locator('[data-mw-link-action="open"]')).not.toHaveAttribute('href');
  expect(await block.textContent()).toBe(text);
});
