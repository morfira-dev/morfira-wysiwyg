import { expect, test } from '@playwright/test';

test('Russian narrow homepage applies table and merged-cell properties in one Undo', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 });
  await page.goto('/ru/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const lab = page.locator('.lab-contextual-table');
  await lab.locator('summary').click();
  await lab.getByRole('button', { name: 'Загрузить пример контекстной таблицы', exact: true }).click();
  await lab.getByRole('button', { name: 'Выделить область 2 × 2', exact: true }).click();
  const table = content.locator('table[title="Contextual table sample"]');
  const originalText = await table.textContent();
  const form = page.getByRole('form', { name: 'Свойства таблицы', exact: true });
  await expect(form).toBeVisible();
  await form.getByLabel('Ширина таблицы (40–4000px или 1–100%)', { exact: true }).fill('60%');
  await form.getByLabel('Расположение таблицы', { exact: true }).selectOption('center');
  await form.getByLabel('Цвет фона ячеек', { exact: true }).fill('#dbeafe');
  await form.getByLabel('Цвет границ ячеек', { exact: true }).fill('#2563eb');
  await form.getByLabel('Вертикальное выравнивание ячеек', { exact: true }).selectOption('middle');
  await form.getByRole('button', { name: 'Применить свойства', exact: true }).click();
  expect(await table.evaluate((node) => ({ width: node.style.width, left: node.style.marginLeft, right: node.style.marginRight }))).toEqual({ width: '60%', left: 'auto', right: 'auto' });
  await expect(table.locator('td[style*="vertical-align"]')).toHaveCount(3);
  await expect(table.locator('td').first()).toHaveCSS('background-color', 'rgb(219, 234, 254)');
  await expect(table.locator('td[rowspan="2"] strong')).toHaveText('Alpha');
  expect(await table.textContent()).toBe(originalText);
  const undo = page.getByRole('toolbar', { name: 'Форматирование', exact: true }).locator('[data-mw-ui-action="undo"]');
  await undo.click();
  expect(await table.evaluate((node) => node.style.width)).toBe('');
  await expect(table.locator('td[style*="vertical-align"]')).toHaveCount(0);
  await expect(table.locator('td[rowspan="2"] strong')).toHaveText('Alpha');
  await expect(undo).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
});

test('English playground preserves mixed cell colors when only table width changes and disables read-only form', async ({ page }) => {
  await page.goto('/playground');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const lab = page.locator('.lab-contextual-table');
  await lab.locator('summary').click();
  await lab.getByRole('button', { name: 'Load contextual table sample', exact: true }).click();
  const table = content.locator('table[title="Contextual table sample"]');
  const form = page.getByRole('form', { name: 'Table properties', exact: true });
  const background = form.getByLabel('Cell background color', { exact: true });
  const width = form.getByLabel('Table width (40–4000px or 1–100%)', { exact: true });
  const apply = form.getByRole('button', { name: 'Apply properties', exact: true });
  await background.fill('#fef3c7');
  await apply.click();
  await lab.getByRole('button', { name: 'Select 2 × 2 region', exact: true }).click();
  await expect(background).toHaveValue('');
  await expect(background).toHaveAttribute('placeholder', 'Mixed values');
  await width.fill('75%');
  await width.press('Enter');
  expect(await table.evaluate((node) => node.style.width)).toBe('75%');
  await expect(table.locator('td').first()).toHaveCSS('background-color', 'rgb(254, 243, 199)');
  expect(await table.locator('td').nth(1).evaluate((node) => node.style.backgroundColor)).toBe('');
  const undo = page.getByRole('toolbar', { name: 'Formatting', exact: true }).locator('[data-mw-ui-action="undo"]');
  await undo.click();
  expect(await table.evaluate((node) => node.style.width)).toBe('');
  await expect(table.locator('td').first()).toHaveCSS('background-color', 'rgb(254, 243, 199)');
  await undo.click();
  expect(await table.locator('td').first().evaluate((node) => node.style.backgroundColor)).toBe('');
  await lab.getByRole('button', { name: 'Return caret to first cell', exact: true }).click();
  await page.getByRole('button', { name: 'Read only', exact: true }).click();
  await expect(width).toBeDisabled();
  await expect(apply).toBeDisabled();
  await expect(content).toHaveAttribute('aria-readonly', 'true');
});
