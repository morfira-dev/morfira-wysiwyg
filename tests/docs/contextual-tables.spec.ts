import { expect, test } from '@playwright/test';

test('Russian narrow homepage merges a spanning rectangle, preserves rich content and undoes in one step', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 });
  await page.goto('/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const toggle = page.getByRole('checkbox', { name: 'Контекстная панель таблиц', exact: true });
  await expect(toggle).toBeChecked();
  const lab = page.locator('.lab-contextual-table');
  await lab.locator('summary').click();
  await lab.getByRole('button', { name: 'Загрузить пример контекстной таблицы', exact: true }).click();
  const table = content.locator('table[title="Contextual table sample"]');
  const panel = page.locator('.mw-contextual-table');
  await expect(panel).toBeVisible();
  await expect(panel.locator('[data-mw-table-action="merge"]')).toBeDisabled();
  await expect(panel.locator('[data-mw-table-action="split"]')).toBeEnabled();
  const toolbar = page.getByRole('toolbar', { name: 'Форматирование', exact: true });
  const undo = toolbar.locator('[data-mw-ui-action="undo"]');
  await expect(undo).toBeDisabled();
  const originalText = await table.textContent();
  await lab.getByRole('button', { name: 'Выделить область 2 × 2', exact: true }).click();
  await expect(table.locator('[data-mw-selected]')).toHaveCount(3);
  await expect(panel.locator('[data-mw-table-action="merge"]')).toHaveText('Объединить ячейки');
  await panel.locator('[data-mw-table-action="merge"]').click();
  const merged = table.locator('td[rowspan="2"][colspan="2"]');
  await expect(merged).toHaveCount(1);
  await expect(merged.locator('strong')).toHaveText('Alpha');
  await expect(merged.locator('em')).toHaveText('Beta');
  await expect(merged.locator('u')).toHaveText('Gamma');
  await expect(table.locator('td').filter({ hasText: 'Outside' })).toHaveCount(3);
  await expect(panel).toBeHidden();
  await undo.click();
  await expect(table.locator('td')).toHaveCount(8);
  await expect(table.locator('td[rowspan="2"]')).toHaveCount(1);
  expect(await table.textContent()).toBe(originalText);
  await expect(table.locator('em')).toHaveText('Beta');
  await expect(table.locator('u')).toHaveText('Gamma');
  await expect(undo).toBeDisabled();
  await lab.getByRole('button', { name: 'Вернуть курсор в первую ячейку', exact: true }).click();
  await panel.locator('[data-mw-table-action="split"]').click();
  await expect(table.locator('td')).toHaveCount(9);
  await expect(table.locator('[rowspan]')).toHaveCount(0);
  await expect(table.locator('strong')).toHaveText('Alpha');
  await toggle.uncheck();
  await expect(panel).toHaveCount(0);
  await expect(undo).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
});

test('English dark playground enters table tools by keyboard, edits rows/columns and cleans up read-only UI', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/en/playground');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  await page.getByRole('button', { name: 'Toggle theme', exact: true }).click();
  const lab = page.locator('.lab-contextual-table');
  await lab.locator('summary').click();
  await lab.getByRole('button', { name: 'Load contextual table sample', exact: true }).click();
  const table = content.locator('table[title="Contextual table sample"]');
  const panel = page.locator('.mw-contextual-table');
  const reset = lab.getByRole('button', { name: 'Return caret to first cell', exact: true });
  await page.keyboard.press('Alt+F10');
  const above = panel.locator('[data-mw-table-action="rowAbove"]');
  await expect(above).toBeFocused();
  await expect(above).toHaveText('Insert row above');
  expect(await panel.evaluate((node) => getComputedStyle(node).getPropertyValue('--mw-toolbar-bg').trim())).toBe('#222839');
  await above.press('Escape');
  await expect(panel).toBeHidden();
  await expect(content).toBeFocused();
  await page.keyboard.press('Alt+F10');
  await expect(above).toBeFocused();
  await above.press('Enter');
  await expect(table.locator('tr')).toHaveCount(4);
  await expect(table.locator('td[rowspan="2"] strong')).toHaveText('Alpha');
  await expect(panel).toBeHidden();
  const undo = page.getByRole('toolbar', { name: 'Formatting', exact: true }).locator('[data-mw-ui-action="undo"]');
  await undo.click();
  await expect(table.locator('tr')).toHaveCount(3);
  await reset.click();
  await panel.locator('[data-mw-table-action="columnRight"]').click();
  await expect(table.locator('tr').last().locator('td')).toHaveCount(4);
  await expect(table.locator('td').filter({ hasText: 'Outside' })).toHaveCount(3);
  await undo.click();
  await expect(table.locator('tr').last().locator('td')).toHaveCount(3);
  await expect(undo).toBeDisabled();
  await reset.click();
  await page.getByRole('button', { name: 'Read only', exact: true }).click();
  await expect(content).toHaveAttribute('aria-readonly', 'true');
  await expect(panel).toBeHidden();
  await expect(table.locator('td')).toHaveCount(8);
  const toggle = page.getByRole('checkbox', { name: 'Contextual table toolbar', exact: true });
  await toggle.uncheck();
  await expect(panel).toHaveCount(0);
  await toggle.check();
  await expect(panel).toBeHidden();
  await expect(table.locator('strong')).toHaveText('Alpha');
});
