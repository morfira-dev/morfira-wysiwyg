import { expect, test } from '@playwright/test';

test('Russian narrow homepage edits selected image metadata with Enter, preserves rich caption and undoes removal', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 });
  await page.goto('/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const toggle = page.getByRole('checkbox', { name: 'Контекстные свойства изображения', exact: true });
  await expect(toggle).toBeChecked();
  const lab = page.locator('.lab-contextual-image');
  await lab.locator('summary').click();
  await lab.getByRole('button', { name: 'Загрузить пример свойств изображения', exact: true }).click();
  const figure = content.locator('[title="Contextual image sample"]');
  const image = figure.locator('img');
  await image.click();
  const panel = page.locator('.mw-contextual-image');
  await expect(panel).toBeVisible();
  await expect(panel.locator('.mw-contextual-image-summary')).toHaveText('Знак Morfira');
  await expect(panel.locator('img')).toHaveCount(0);
  await expect(content.locator('img')).toHaveCount(1);
  const originalText = await content.textContent();
  await panel.getByRole('button', { name: 'Свойства изображения', exact: true }).click();
  const form = panel.getByRole('form');
  await expect(form.getByLabel('URL изображения', { exact: true })).toBeFocused();
  await expect(form.getByRole('button', { name: 'Вставить изображение', exact: true })).toHaveCount(0);
  await expect(form.locator('input[type="file"]')).toHaveCount(0);
  await form.getByLabel('Alt', { exact: true }).fill('Обновлённый знак');
  const width = form.getByLabel('Ширина изображения', { exact: true });
  await width.fill('160');
  await width.press('Enter');
  await expect(image).toHaveAttribute('alt', 'Обновлённый знак');
  await expect(image).toHaveAttribute('width', '160');
  await expect(image).toHaveAttribute('height', '80');
  await expect(figure.locator('figcaption em')).toHaveText('Исходная подпись');
  await expect(content.locator('img')).toHaveCount(1);
  expect(await content.textContent()).toBe(originalText);
  const toolbar = page.getByRole('toolbar', { name: 'Форматирование', exact: true });
  const undo = toolbar.locator('[data-mw-ui-action="undo"]');
  const redo = toolbar.locator('[data-mw-ui-action="redo"]');
  await undo.click();
  await expect(image).toHaveAttribute('alt', 'Знак Morfira');
  await expect(image).toHaveAttribute('width', '120');
  await expect(undo).toBeDisabled();
  await redo.click();
  await expect(image).toHaveAttribute('width', '160');
  await image.click();
  await expect(panel).toBeVisible();
  await panel.getByRole('button', { name: 'Удалить изображение', exact: true }).click();
  await expect(figure).toHaveCount(0);
  await expect(content).toContainText('До изображения');
  await expect(content).toContainText('После изображения');
  await undo.click();
  await expect(image).toHaveAttribute('alt', 'Обновлённый знак');
  await expect(figure.locator('figcaption em')).toHaveText('Исходная подпись');
  await toggle.uncheck();
  await expect(panel).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
});

test('English dark playground selects the native image range, cancels a draft with Escape and guards read-only properties', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/en/playground');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  await page.getByRole('button', { name: 'Toggle theme', exact: true }).click();
  const lab = page.locator('.lab-contextual-image');
  await lab.locator('summary').click();
  await lab.getByRole('button', { name: 'Load image properties sample', exact: true }).click();
  await lab.getByRole('button', { name: 'Select sample image', exact: true }).click();
  const figure = content.locator('[title="Contextual image sample"]');
  const image = figure.locator('img');
  const panel = page.locator('.mw-contextual-image');
  await page.keyboard.press('Alt+F10');
  const properties = panel.getByRole('button', { name: 'Image properties', exact: true });
  await expect(properties).toBeFocused();
  await properties.press('Enter');
  const form = panel.getByRole('form');
  const alt = form.getByLabel('Alt', { exact: true });
  await expect(form.getByLabel('Image URL', { exact: true })).toBeFocused();
  await alt.fill('Uncommitted');
  await alt.press('Escape');
  await expect(panel).toBeHidden();
  await expect(image).toHaveAttribute('alt', 'Morfira mark');
  expect(await content.evaluate((surface) => {
    const selection = document.getSelection();
    if (selection?.rangeCount !== 1) return false;
    const range = selection.getRangeAt(0);
    const image = surface.querySelector('[title="Contextual image sample"] img')!;
    return document.activeElement === surface && range.startContainer === image.parentNode
      && range.startContainer === range.endContainer && range.endOffset === range.startOffset + 1
      && range.startContainer.childNodes[range.startOffset] === image;
  })).toBe(true);
  await page.keyboard.press('Alt+F10');
  await expect(properties).toBeFocused();
  expect(await panel.evaluate((node) => getComputedStyle(node).getPropertyValue('--mw-toolbar-bg').trim())).toBe('#222839');
  const box = await panel.boundingBox();
  expect(box).not.toBeNull();
  expect(box!.x).toBeGreaterThanOrEqual(0);
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width + 1);
  await page.getByRole('button', { name: 'Read only', exact: true }).click();
  await expect(content).toHaveAttribute('aria-readonly', 'true');
  await image.click();
  // Read-only can retain disabled summary or dismiss when the native surface loses focus.
  await expect(panel.locator('button:enabled:visible')).toHaveCount(0);
  await expect(panel.getByRole('form')).toHaveCount(0);
  await expect(image).toHaveAttribute('alt', 'Morfira mark');
  await expect(figure.locator('figcaption em')).toHaveText('Original caption');
  await expect(page.getByRole('toolbar', { name: 'Formatting', exact: true }).locator('[data-mw-ui-action="undo"]')).toBeDisabled();
  await page.getByRole('checkbox', { name: 'Contextual image properties', exact: true }).uncheck();
  await expect(panel).toHaveCount(0);
  await expect(content.locator('img')).toHaveCount(1);
});
