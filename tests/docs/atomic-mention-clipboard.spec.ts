for (const english of [false, true]) test(`atomic mention nested branches through ${english ? 'English' : 'Russian'} demo controls`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const panel = page.locator('.lab-mention-clipboard');
  await panel.locator('summary').click();
  const button = (ru: string, en: string) => panel.getByRole('button', { name: t(ru, en), exact: true });
  const undo = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]');
  await button('Загрузить буфер с вложенными ветками', 'Load nested branch clipboard sample').click();
  const source = content.locator('ol[title="Mention list source"]');
  const destination = content.locator('ul[title="Mention list destination"]');
  const destinationBranch = await destination.locator('[title="Mention list destination branch"]').elementHandle();
  await button('Выделить пункты назад', 'Select list items backward').click();
  const selected = await page.evaluate(() => document.getSelection()?.toString());
  const original = await content.innerHTML();
  await button('Копировать в память', 'Copy to memory').click();
  await expect(content).toHaveJSProperty('innerHTML', original);
  await expect.poll(() => page.evaluate(() => document.getSelection()?.toString())).toBe(selected);
  const copiedHTML = await panel.locator('[data-mention-clipboard-html]').textContent();
  for (const id of ['anna', 'elena', 'deep', 'liam', 'boris']) expect(copiedHTML).toContain(`data-mention-id="${id}"`);
  expect(copiedHTML).toContain('Mention copied first branch');
  expect(copiedHTML).toContain('Mention copied deep branch');
  expect(copiedHTML).toContain('Mention copied middle branch');
  expect(copiedHTML).not.toMatch(/contenteditable|Retained body|Retained branch/);
  await expect(panel.locator('[data-mention-clipboard-text]')).toHaveJSProperty('textContent', '@Anna first\n@Elena branch\n@Deep\nShared item\n@Liam middle\n@Boris');
  await button('Выделить целевые пункты', 'Select destination items').click();
  await button('Вставить с ID', 'Paste with ID').click();
  await expect(destination.locator(':scope > li')).toHaveCount(3);
  const firstBranch = destination.locator(':scope > li:first-child > ul[title="Mention copied first branch"]');
  await expect(firstBranch.locator(':scope > li > ol[title="Mention copied deep branch"]')).toHaveAttribute('start', '5');
  await expect(firstBranch.locator('[data-mention-id="elena"]')).toHaveText('@Elena');
  await expect(firstBranch.locator('[data-mention-id="deep"]')).toHaveText('@Deep');
  await expect(destination.locator(':scope > li:nth-child(2) > ol[title="Mention copied middle branch"]')).toHaveAttribute('start', '7');
  await expect(destination.locator('[data-mention-id]')).toHaveCount(5);
  await expect(destination.locator('[title="Mention list destination body"]')).toHaveText('Destination body');
  expect(await destinationBranch!.evaluate((node) => node === document.querySelector('ul[title="Mention list destination"] [title="Mention list destination branch"]'))).toBe(true);
  await expect(destination.locator('li > li')).toHaveCount(0);
  await undo.click();
  await expect(content).toHaveJSProperty('innerHTML', original);
  const retained = await source.locator('[title="Mention list retained branch"]').elementHandle();
  await button('Выделить пункты назад', 'Select list items backward').click();
  await button('Вырезать в память', 'Cut to memory').click();
  await expect(source.locator(':scope > li')).toHaveCount(1);
  await expect(source.locator('[title^="Mention copied"]')).toHaveCount(0);
  await expect(source.locator('[data-mention-id]')).toHaveCount(0);
  await expect(source.locator('[title="Mention list retained body"]')).toHaveText('Retained body');
  expect(await retained!.evaluate((node) => node === document.querySelector('ol[title="Mention list source"] [title="Mention list retained branch"]'))).toBe(true);
  await undo.click();
  await expect(content).toHaveJSProperty('innerHTML', original);
});
