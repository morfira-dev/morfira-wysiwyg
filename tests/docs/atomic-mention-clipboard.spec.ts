import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`atomic mention memory clipboard through ${english ? 'English' : 'Russian'} demo controls`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const panel = page.locator('.lab-mention-clipboard');
  await panel.locator('summary').click();
  const button = (ru: string, en: string) => panel.getByRole('button', { name: t(ru, en), exact: true });
  await button('Загрузить пример буфера', 'Load clipboard sample').click();
  const anna = content.locator('[data-mw-node="morfira:mention"][data-mention-id="anna"]');
  await button('Выделить @Anna для буфера', 'Select @Anna for clipboard').click();
  const selected = await page.evaluate(() => document.getSelection()?.toString());
  const before = await content.innerHTML();
  await button('Копировать в память', 'Copy to memory').click();
  await expect(content).toHaveJSProperty('innerHTML', before);
  await expect.poll(() => page.evaluate(() => document.getSelection()?.toString())).toBe(selected);
  await expect(panel.locator('[data-mention-clipboard-html]')).toContainText('data-mention-id="anna"');
  await expect(panel.locator('[data-mention-clipboard-html]')).not.toContainText('contenteditable');
  await expect(panel.locator('[data-mention-clipboard-text]')).toHaveText('@Anna');
  await button('Место вставки после @Anna', 'Paste position after @Anna').click();
  await button('Вставить с ID', 'Paste with ID').click();
  await expect(anna).toHaveCount(2);
  await expect(anna.first()).toHaveAttribute('contenteditable', 'false');
  await expect(anna.last()).toHaveAttribute('contenteditable', 'false');
  await expect(panel.locator('[data-mention-clipboard-references]')).toContainText('"id": "anna"');
  await button('Вставить только текст', 'Paste plain text').click();
  await expect(anna).toHaveCount(2);
  await expect(content).toContainText('@Anna@Anna@Anna');
  await button('Выделить @Anna для буфера', 'Select @Anna for clipboard').click();
  await button('Вырезать в память', 'Cut to memory').click();
  await expect(anna).toHaveCount(1);
  await page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]').click();
  await expect(anna).toHaveCount(2);
  await page.getByRole('button', { name: t('Только чтение', 'Read only'), exact: true }).click();
  await expect(button('Копировать в память', 'Copy to memory')).toBeEnabled();
  await expect(button('Вырезать в память', 'Cut to memory')).toBeDisabled();
  await expect(button('Вставить с ID', 'Paste with ID')).toBeDisabled();
  await panel.getByRole('link', { name: t('Буфер, безопасность и ограничения', 'Clipboard, safety and boundaries'), exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`${english ? '/en' : ''}/atomic-mention-clipboard$`));
  await expect(page.locator('.vp-doc')).toContainText('text/plain');
  await expect(page.locator('.vp-doc')).toContainText('mentionClipboardCommands');
});

for (const english of [false, true]) test(`atomic mention block transfers through ${english ? 'English' : 'Russian'} demo controls`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const panel = page.locator('.lab-mention-clipboard');
  await panel.locator('summary').click();
  const button = (ru: string, en: string) => panel.getByRole('button', { name: t(ru, en), exact: true });
  const undo = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]');
  await button('Загрузить буфер между блоками', 'Load block clipboard sample').click();
  await button('Выделить блоки назад', 'Select blocks backward').click();
  const selected = await page.evaluate(() => document.getSelection()?.toString());
  const original = await content.innerHTML();
  await button('Копировать в память', 'Copy to memory').click();
  await expect(content).toHaveJSProperty('innerHTML', original);
  await expect.poll(() => page.evaluate(() => document.getSelection()?.toString())).toBe(selected);
  const copiedHTML = await panel.locator('[data-mention-clipboard-html]').textContent();
  expect(copiedHTML).toContain('<h3');
  expect(copiedHTML).toContain('data-mention-id="anna"');
  expect(copiedHTML).toContain('data-mention-id="boris"');
  expect(copiedHTML).not.toContain('contenteditable');
  await expect(panel.locator('[data-mention-clipboard-text]')).toHaveJSProperty('textContent', '@Anna first\nShared heading\n@Boris');
  await button('Выделить целевые блоки', 'Select destination blocks').click();
  await button('Вставить с ID', 'Paste with ID').click();
  await expect(content.locator('[data-mention-id="anna"]')).toHaveCount(2);
  await expect(content.locator('[data-mention-id="boris"]')).toHaveCount(2);
  await expect(content.locator('h3')).toHaveCount(2);
  await expect(content.locator('[title="Mention block destination end"]')).toHaveCount(0);
  await expect(content.locator('[title="Mention block destination"]')).toContainText('Target @Anna first');
  await expect(content.locator(':scope > p:last-child')).toContainText('@Boris tail');
  await undo.click();
  await expect(content).toHaveJSProperty('innerHTML', original);
  await button('Выделить блоки назад', 'Select blocks backward').click();
  await button('Вырезать в память', 'Cut to memory').click();
  await expect(content.locator('[data-mention-id]')).toHaveCount(0);
  await expect(content.locator('[title="Mention block middle"]')).toHaveCount(0);
  await expect(content.locator('[title="Mention block end"]')).toHaveCount(0);
  await expect(content.locator('[title="Mention block start"]')).toHaveText('Before  after');
  await expect(content.locator('[title="Mention block destination end"]')).toHaveCount(1);
  await undo.click();
  await expect(content).toHaveJSProperty('innerHTML', original);
});

for (const english of [false, true]) test(`atomic mention list transfers through ${english ? 'English' : 'Russian'} demo controls`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const panel = page.locator('.lab-mention-clipboard');
  await panel.locator('summary').click();
  const button = (ru: string, en: string) => panel.getByRole('button', { name: t(ru, en), exact: true });
  const undo = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]');
  await button('Загрузить буфер между пунктами', 'Load list clipboard sample').click();
  const source = content.locator('ol[title="Mention list source"]');
  const destination = content.locator('ul[title="Mention list destination"]');
  await expect(source).toHaveAttribute('start', '3');
  await button('Выделить пункты назад', 'Select list items backward').click();
  const selected = await page.evaluate(() => document.getSelection()?.toString());
  const original = await content.innerHTML();
  await button('Копировать в память', 'Copy to memory').click();
  await expect(content).toHaveJSProperty('innerHTML', original);
  await expect.poll(() => page.evaluate(() => document.getSelection()?.toString())).toBe(selected);
  const copiedHTML = await panel.locator('[data-mention-clipboard-html]').textContent();
  expect(copiedHTML).toContain('<ol');
  expect(copiedHTML?.match(/<li(?:\s|>)/g)).toHaveLength(3);
  expect(copiedHTML).toContain('data-mention-id="anna"');
  expect(copiedHTML).toContain('data-mention-id="boris"');
  expect(copiedHTML).not.toMatch(/contenteditable|Retained body|Retained branch/);
  await expect(panel.locator('[data-mention-clipboard-text]')).toHaveJSProperty('textContent', '@Anna first\nShared item\n@Boris');
  await button('Выделить целевые пункты', 'Select destination items').click();
  await button('Вставить с ID', 'Paste with ID').click();
  await expect(destination.locator(':scope > li')).toHaveCount(3);
  await expect(destination.locator(':scope > li').first()).toContainText('Target @Anna first');
  await expect(destination.locator(':scope > li').last()).toContainText('@Boris tail');
  await expect(destination.locator('[title="Mention list destination body"]')).toHaveText('Destination body');
  await expect(destination.locator('[title="Mention list destination branch"]')).toHaveText('Destination branch');
  await expect(content.locator('[data-mention-id="anna"]')).toHaveCount(2);
  await expect(content.locator('[data-mention-id="boris"]')).toHaveCount(2);
  await expect(source).toHaveAttribute('start', '3');
  await undo.click();
  await expect(content).toHaveJSProperty('innerHTML', original);
  await button('Выделить пункты назад', 'Select list items backward').click();
  await button('Вырезать в память', 'Cut to memory').click();
  await expect(source.locator(':scope > li')).toHaveCount(1);
  await expect(source.locator('[data-mention-id]')).toHaveCount(0);
  await expect(source.locator('[title="Mention list start"] > p').first()).toHaveText('Before  after');
  await expect(source.locator('[title="Mention list retained body"]')).toHaveText('Retained body');
  await expect(source.locator('[title="Mention list retained branch"]')).toHaveText('Retained branch');
  await expect(destination.locator(':scope > li')).toHaveCount(2);
  await undo.click();
  await expect(content).toHaveJSProperty('innerHTML', original);
});
