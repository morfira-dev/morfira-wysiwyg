import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`atomic mention memory clipboard through ${english ? 'English' : 'Russian'} demo controls`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const panel = page.locator('.lab-mention-clipboard');
  await panel.locator('summary').click();
  const button = (ru: string, en: string) => panel.getByRole('button', { name: t(ru, en), exact: true });
  await button('Загрузить пример буфера', 'Load clipboard sample').click();
  const anna = content.locator('[data-mw-node="morfira:mention"][data-mention-id="anna"]');
  await button('Выделить @Anna для буфера', 'Select @Anna for clipboard').click();
  const selected = await page.evaluate(() => document.getSelection()?.toString());
  const before = await content.innerHTML();
  await button('Копировать в память', 'Copy to memory').click();
  await expect(content).toHaveJSProperty('innerHTML', before);
  await expect.poll(() => page.evaluate(() => document.getSelection()?.toString())).toBe(selected);
  await expect(panel.locator('[data-mention-clipboard-html]')).toContainText('data-mention-id="anna"');
  await expect(panel.locator('[data-mention-clipboard-html]')).not.toContainText('contenteditable');
  await expect(panel.locator('[data-mention-clipboard-text]')).toHaveText('@Anna');
  await button('Место вставки после @Anna', 'Paste position after @Anna').click();
  await button('Вставить с ID', 'Paste with ID').click();
  await expect(anna).toHaveCount(2);
  await expect(anna.first()).toHaveAttribute('contenteditable', 'false');
  await expect(anna.last()).toHaveAttribute('contenteditable', 'false');
  await expect(panel.locator('[data-mention-clipboard-references]')).toContainText('"id": "anna"');
  await button('Вставить только текст', 'Paste plain text').click();
  await expect(anna).toHaveCount(2);
  await expect(content).toContainText('@Anna@Anna@Anna');
  await button('Выделить @Anna для буфера', 'Select @Anna for clipboard').click();
  await button('Вырезать в память', 'Cut to memory').click();
  await expect(anna).toHaveCount(1);
  await page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]').click();
  await expect(anna).toHaveCount(2);
  await page.getByRole('button', { name: t('Только чтение', 'Read only'), exact: true }).click();
  await expect(button('Копировать в память', 'Copy to memory')).toBeEnabled();
  await expect(button('Вырезать в память', 'Cut to memory')).toBeDisabled();
  await expect(button('Вставить с ID', 'Paste with ID')).toBeDisabled();
  await panel.getByRole('link', { name: t('Буфер, безопасность и ограничения', 'Clipboard, safety and boundaries'), exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`${english ? '/en' : ''}/atomic-mention-clipboard$`));
  await expect(page.locator('.vp-doc')).toContainText('text/plain');
  await expect(page.locator('.vp-doc')).toContainText('mentionClipboardCommands');
});
