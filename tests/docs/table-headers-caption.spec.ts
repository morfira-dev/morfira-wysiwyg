import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`table header column and literal caption in ${english ? 'English playground' : 'Russian homepage'}`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/playground' : '/ru/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  await page.getByLabel(t('Пример документа', 'Document sample'), { exact: true }).selectOption('tables');
  await page.getByRole('button', { name: t('Загрузить пример', 'Load sample'), exact: true }).click();
  const table = content.locator('table[title="Table headers sample"]');
  await expect(table.locator('thead th[scope="col"]')).toHaveCount(3);
  const originalCaption = t('Возможности таблиц Morfira', 'Morfira table capabilities');
  await expect(table.locator('caption')).toHaveText(originalCaption);
  await table.locator('tbody td[rowspan="2"]').click();
  const form = page.getByRole('form', { name: t('Свойства таблицы', 'Table properties'), exact: true });
  const headerRow = form.getByLabel(t('Строка заголовков', 'Header row'), { exact: true });
  const headerColumn = form.getByLabel(t('Столбец заголовков', 'Header column'), { exact: true });
  const caption = form.getByLabel(t('Подпись таблицы', 'Table caption'), { exact: true });
  const apply = form.getByRole('button', { name: t('Применить свойства', 'Apply properties'), exact: true });
  await expect(headerRow).toHaveValue('true');
  await expect(headerColumn).toHaveValue('');
  await headerColumn.selectOption('true');
  const literal = t('План <img src="/unsafe.png">\nВыпуск', 'Plan <img src="/unsafe.png">\nRelease');
  await caption.fill(literal);
  await apply.click();
  await expect(table.locator('caption')).toHaveText(literal);
  await expect(table.locator('caption img')).toHaveCount(0);
  await expect(table.locator('thead th[scope="col"]')).toHaveCount(3);
  await expect(table.locator('tbody th[scope="row"][rowspan="2"] strong')).toHaveText(t('Таблицы', 'Tables'));
  await expect(table.locator('tr')).toHaveCount(3);
  const undo = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]');
  await undo.click();
  await expect(table.locator('caption')).toHaveText(originalCaption);
  await expect(table.locator('tbody th')).toHaveCount(0);
  await expect(table.locator('tbody td[rowspan="2"] strong')).toHaveText(t('Таблицы', 'Tables'));
  await expect(undo).toBeDisabled();
  await table.locator('tbody td[rowspan="2"]').click();
  await headerRow.selectOption('');
  await caption.fill('');
  await apply.click();
  await expect(table.locator('caption')).toHaveCount(0);
  await expect(table.locator('thead td')).toHaveCount(3);
  await expect(table.locator('tbody td[rowspan="2"] strong')).toHaveText(t('Таблицы', 'Tables'));
  await undo.click();
  await expect(table.locator('caption')).toHaveText(originalCaption);
  await expect(table.locator('thead th[scope="col"]')).toHaveCount(3);
});
