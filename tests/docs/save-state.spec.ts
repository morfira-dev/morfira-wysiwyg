import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`save-state demo keeps newer edits dirty and retries current content in ${english ? 'English' : 'Russian'}`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  if (!english) await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const panel = page.locator('.lab-save-state');
  await panel.locator('summary').click();
  const status = panel.locator('.mw-save-state').getByRole('status');
  const save = panel.locator('.mw-save-state').getByRole('button', { name: t('Сохранить', 'Save'), exact: true });
  const prepare = panel.getByRole('button', { name: t('Подготовить несохранённый пример', 'Prepare unsaved sample'), exact: true });
  await prepare.click();
  await expect(status).toHaveText(t('Есть несохранённые изменения', 'Unsaved changes'));
  await save.click();
  await expect(status).toHaveText(t('Сохранение…', 'Saving…'));
  await panel.getByRole('button', { name: t('Изменить во время сохранения', 'Edit while saving'), exact: true }).click();
  await expect(content).toHaveText(t('Черновик + правка + новая правка', 'Draft + edit + newer edit'));
  await expect(status).toHaveText(t('Есть несохранённые изменения', 'Unsaved changes'));
  const editedHTML = await content.innerHTML();
  await save.click();
  await expect(status).toHaveText(t('Сохранено', 'Saved'));
  expect(await content.innerHTML()).toBe(editedHTML);
  await prepare.click();
  await panel.getByLabel(t('Следующее сохранение с ошибкой', 'Fail the next save'), { exact: true }).check();
  await save.click();
  await expect(status).toHaveText(t('Не удалось сохранить. Повторите попытку.', 'Save failed. Try again.'));
  await panel.locator('.mw-save-state').getByRole('button', { name: t('Повторить', 'Retry'), exact: true }).click();
  await expect(status).toHaveText(t('Сохранено', 'Saved'));
  await expect(content).toHaveText(t('Черновик + правка', 'Draft + edit'));
  await panel.getByRole('button', { name: t('Приложение подтверждает текущую версию', 'Application acknowledges current revision'), exact: true }).click();
  await prepare.click();
  const readonlyHTML = await content.innerHTML();
  await page.getByRole('button', { name: t('Только чтение', 'Read only'), exact: true }).click();
  await expect(content).toHaveAttribute('contenteditable', 'false');
  await expect(save).toBeEnabled();
  await save.click();
  await expect(status).toHaveText(t('Сохранено', 'Saved'));
  expect(await content.innerHTML()).toBe(readonlyHTML);
  await panel.getByRole('link', { name: t('Контракт сохранения и ответственность сервера', 'Save contract and server responsibilities'), exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`${english ? '/en' : ''}/save-state$`));
  await expect(page.locator('.vp-doc')).toContainText('SaveStateSnapshot');
});
