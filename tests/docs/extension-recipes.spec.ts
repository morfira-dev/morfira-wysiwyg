import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`application recipes expose ID nodes, local services and conflict recovery (${english ? 'EN' : 'RU'})`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  const errors: string[] = [];
  const writes: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (request.method() === 'POST') writes.push(request.url()); });
  await page.goto(english ? '/en/extension-recipes' : '/extension-recipes');
  const demo = page.locator('.recipes-example');
  const content = demo.locator('.mw-content');
  const button = (ru: string, en: string) => demo.getByRole('button', { name: t(ru, en), exact: true });
  await button('Вставить узел с ID', 'Insert node with ID').click();
  await expect(content.locator('[data-record-id="issue_42"]')).toHaveText('ISSUE-42');
  await button('Найти @Alice', 'Find @Alice').click();
  await page.getByRole('option', { name: /Alice/ }).click();
  await expect(demo.locator('.recipe-mentions')).toContainText('user_1:');
  await button('Имитировать загрузку', 'Simulate upload').click();
  await expect(content.locator('img')).toHaveAttribute('src', '/logo.svg');
  await expect(demo).toContainText(t('Прогресс имитации: 100%', 'Simulated progress: 100%'));
  await button('Ленивая подсветка', 'Lazy highlighting').click();
  await expect(demo.locator('.recipe-code-view .mw-code-token-keyword')).toHaveText('const');
  await expect(content.locator('.mw-code-token-keyword')).toHaveCount(0);
  await button('Изменить на сервере', 'Simulate remote edit').click();
  await button('Сохранить', 'Save').click();
  await expect(demo.getByRole('alert')).toContainText(t('Конфликт версий', 'Version conflict'));
  await expect(demo.locator('.recipes-save-status')).toContainText(t('Локальная версия: v1', 'Local version: v1'));
  await button('Повторить сохранение', 'Retry save').click();
  await expect(demo.locator('.recipes-save-status')).toContainText('error');
  await button('Загрузить серверную версию', 'Reload server version').click();
  await expect(content).toHaveText('Remote revision 2');
  await expect(demo.getByRole('alert')).toHaveCount(0);
  await button('Локальное изменение', 'Local edit').click();
  await button('Сохранить', 'Save').click();
  await expect(demo.locator('.recipes-save-status')).toContainText(t('Локальная версия: v3', 'Local version: v3'));
  await expect(demo.locator('.recipes-save-status')).toContainText('saved');
  expect(writes).toEqual([]);
  expect(errors).toEqual([]);
});
