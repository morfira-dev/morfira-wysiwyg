import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`ready insertion presentation and nonmodal search in ${english ? 'English' : 'Russian'}`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  if (!english) await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(english ? '/playground' : '/ru/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  await page.getByLabel(t('Пример документа', 'Document sample'), { exact: true }).selectOption('empty');
  await page.getByRole('button', { name: t('Загрузить пример', 'Load sample'), exact: true }).click();
  await content.click();
  const toolbar = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true });
  await toolbar.locator('[data-mw-ui-action="image"]').click();
  const dialog = page.locator('.mw-image-dialog[open]');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: t('Вставить изображение', 'Insert image'), exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(content.locator('img')).toHaveAttribute('src', '/logo.svg');
  await toolbar.locator('[data-mw-ui-action="undo"]').click();
  await expect(content.locator('img')).toHaveCount(0);
  await content.click();
  await toolbar.locator('[data-mw-ui-action="table"]').click();
  const popup = page.locator('.demo-toolbar-host .mw-ui-panel');
  await expect(popup).toHaveClass(/mw-ui-panel-popover/);
  const bounds = await popup.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width);
  await page.keyboard.press('Escape');
  await expect(popup).toBeHidden();
  await toolbar.locator('[data-mw-ui-action="search"]').click();
  await expect(popup).toHaveClass(/mw-ui-search-docked/);
  await expect(page.locator('dialog[open]')).toHaveCount(0);
  await content.click();
  await expect(content).toBeFocused();
  await expect(popup).toBeVisible();
  const panelBounds = await popup.boundingBox();
  const editorBounds = await content.boundingBox();
  expect(panelBounds!.y + panelBounds!.height).toBeLessThanOrEqual(editorBounds!.y + 1);
  await page.keyboard.type('Visible document');
  await expect(content).toHaveText('Visible document');
  await expect(popup).toBeVisible();
});
