import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`merged-cell padding and independent border styles in ${english ? 'English playground' : 'Russian homepage'}`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/playground' : '/ru/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const lab = page.locator('.lab-contextual-table');
  await lab.locator('summary').click();
  await lab.getByRole('button', { name: t('Загрузить пример контекстной таблицы', 'Load contextual table sample'), exact: true }).click();
  await lab.getByRole('button', { name: t('Выделить область 2 × 2', 'Select 2 × 2 region'), exact: true }).click();
  const table = content.locator('table[title="Contextual table sample"]');
  const original = await table.textContent();
  const form = page.getByRole('form', { name: t('Свойства таблицы', 'Table properties'), exact: true });
  const padding = form.getByLabel(t('Отступы ячеек (0–48px)', 'Cell padding (0–48px)'), { exact: true });
  const width = form.getByLabel(t('Толщина границ (0–12px)', 'Border width (0–12px)'), { exact: true });
  const style = form.getByLabel(t('Стиль границ', 'Border style'), { exact: true });
  const color = form.getByLabel(t('Цвет границ ячеек', 'Cell border color'), { exact: true });
  const apply = form.getByRole('button', { name: t('Применить свойства', 'Apply properties'), exact: true });
  await padding.fill('8px');
  await width.fill('2px');
  await style.selectOption('dashed');
  await color.fill('#2563eb');
  await apply.click();
  const chosen = table.locator('td').filter({ has: page.locator('strong,em,u') });
  expect(await chosen.evaluateAll((cells) => cells.map((cell) => ({ padding: cell.style.padding, width: cell.style.borderWidth, style: cell.style.borderStyle })))).toEqual(Array.from({ length: 3 }, () => ({ padding: '8px', width: '2px', style: 'dashed' })));
  const outside = table.locator('td').filter({ hasText: /^Outside [ABC]$/ });
  expect(await outside.evaluateAll((cells) => cells.every((cell) => !cell.style.padding && !cell.style.borderWidth && !cell.style.borderStyle))).toBe(true);
  await expect(table.locator('td[rowspan="2"] strong')).toHaveText('Alpha');
  expect(await table.textContent()).toBe(original);
  const undo = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]');
  await undo.click();
  expect(await table.locator('td').evaluateAll((cells) => cells.every((cell) => !cell.style.padding && !cell.style.borderWidth && !cell.style.borderStyle))).toBe(true);
  await expect(undo).toBeDisabled();
  await lab.getByRole('button', { name: t('Выделить область 2 × 2', 'Select 2 × 2 region'), exact: true }).click();
  await padding.fill('8px');
  await width.fill('2px');
  await style.selectOption('dashed');
  await color.fill('#2563eb');
  await apply.click();
  await padding.fill('');
  await apply.click();
  expect(await chosen.evaluateAll((cells) => cells.map((cell) => ({ padding: cell.style.padding, width: cell.style.borderWidth, style: cell.style.borderStyle, color: cell.style.borderColor })))).toEqual(Array.from({ length: 3 }, () => ({ padding: '', width: '2px', style: 'dashed', color: 'rgb(37, 99, 235)' })));
  await undo.click();
  expect(await chosen.evaluateAll((cells) => cells.every((cell) => cell.style.padding === '8px'))).toBe(true);
  await expect(page.locator('.lab-tables')).toContainText(t('Отступ одинаковый для четырёх сторон', 'Padding is uniform on four sides'));
});
