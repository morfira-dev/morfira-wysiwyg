import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`image resize handles preview, commit and cancel on ${english ? 'English playground' : 'Russian homepage'}`, async ({ page }) => {
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/en/playground' : '/');
  const content = page.locator('.mw-content');
  await expect(content).toBeVisible();
  const enabled = page.getByRole('checkbox', { name: t('Маркеры размера изображения', 'Image resize handles'), exact: true });
  await expect(enabled).toBeChecked();
  await page.getByLabel(t('Пример документа', 'Document sample'), { exact: true }).selectOption('images');
  await page.getByRole('button', { name: t('Загрузить пример', 'Load sample'), exact: true }).click();
  const image = content.locator('figure img');
  await image.scrollIntoViewIfNeeded();
  await image.click();
  const handles = page.locator('.mw-image-resize');
  const corner = handles.locator('[data-mw-resize-corner="se"]');
  await expect(corner).toBeVisible();
  let box = (await corner.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 40, box.y + box.height / 2 + 40, { steps: 4 });
  await expect(image).toHaveAttribute('width', '160');
  await expect(image).toHaveAttribute('height', '160');
  await expect(handles.locator('.mw-image-resize-frame')).toBeVisible();
  await page.mouse.up();
  await expect(image).toHaveAttribute('width', '200');
  await expect(image).toHaveAttribute('height', '200');
  await expect(content.locator('figcaption')).toHaveText(t('Логотип Morfira — редактируемая подпись', 'Morfira logo — an editable caption'));
  const undo = page.getByRole('toolbar', { name: t('Форматирование', 'Formatting'), exact: true }).locator('[data-mw-ui-action="undo"]');
  await undo.click();
  await expect(image).toHaveAttribute('width', '160');
  await expect(image).toHaveAttribute('height', '160');
  await expect(undo).toBeDisabled();
  await image.click();
  await expect(corner).toBeVisible();
  box = (await corner.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 20, box.y + box.height / 2 + 20, { steps: 2 });
  await page.keyboard.press('Escape');
  await page.mouse.up();
  await expect(image).toHaveAttribute('width', '160');
  await expect(image).toHaveAttribute('height', '160');
  await expect(undo).toBeDisabled();
  await enabled.uncheck();
  await expect(handles).toHaveCount(0);
});
