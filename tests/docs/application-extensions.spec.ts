import { expect, test } from '@playwright/test';

for (const english of [false, true]) test(`application extension controls edit, reload and publish literal values (${english ? 'EN' : 'RU'})`, async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const t = (ru: string, en: string) => english ? en : ru;
  await page.goto(english ? '/application-extensions' : '/ru/application-extensions');
  const demo = page.locator('.application-extensions-example');
  const source = demo.locator('.mw-content');
  await expect(source.locator('[data-mw-node="app:entity"]')).toHaveText('Ada');
  await demo.getByLabel(t('Текст узла', 'Node text'), { exact: true }).fill('Updated Ada');
  await demo.getByLabel(t('ID сущности', 'Entity ID'), { exact: true }).fill('record-43');
  await demo.getByRole('button', { name: t('Обновить выбранный', 'Update inspected'), exact: true }).click();
  await expect(source.locator('[data-mw-node="app:entity"]')).toHaveText('Updated Ada');
  await expect(source.locator('[data-mw-node="app:entity"]')).toHaveAttribute('data-id', 'record-43');
  await expect(demo.getByRole('button', { name: t('Обновить выбранный', 'Update inspected'), exact: true })).toBeDisabled();
  await demo.getByRole('button', { name: t('Отменить', 'Undo'), exact: true }).click();
  await expect(source.locator('[data-mw-node="app:entity"]')).toHaveText('Ada');
  await demo.getByLabel(t('Тип расширения', 'Extension kind'), { exact: true }).selectOption('callout');
  await demo.getByRole('button', { name: t('Выбрать первый узел', 'Inspect first node'), exact: true }).click();
  await demo.getByLabel(t('Текст узла', 'Node text'), { exact: true }).fill('Warning message');
  await demo.getByLabel(t('Тон блока: info или warning', 'Callout tone: info or warning'), { exact: true }).fill('warning');
  await demo.getByRole('button', { name: t('Обновить выбранный', 'Update inspected'), exact: true }).click();
  await expect(source.locator('[data-mw-node="app:callout"]')).toHaveAttribute('data-tone', 'warning');
  await demo.getByRole('button', { name: t('Сохранить JSON', 'Save JSON'), exact: true }).click();
  const before = await source.textContent();
  await demo.getByLabel('customer', { exact: true }).fill('<b>Literal customer</b>');
  await demo.getByLabel('order', { exact: true }).fill('ORDER-99');
  await demo.getByRole('button', { name: t('Показать с переменными', 'Publish with values'), exact: true }).click();
  const reader = demo.locator('.mw-content-view');
  await expect(reader).toContainText('<b>Literal customer</b>');
  await expect(reader).toContainText('ORDER-99');
  await expect(reader.locator('b,script,img,[contenteditable]')).toHaveCount(0);
  expect(await source.textContent()).toBe(before);
  await demo.getByRole('button', { name: t('Загрузить JSON', 'Reload JSON'), exact: true }).click();
  expect(await source.textContent()).toBe(before);
  await demo.getByRole('checkbox', { name: t('Только чтение', 'Read only'), exact: true }).check();
  await expect(source).toHaveAttribute('contenteditable', 'false');
  await expect(demo.getByRole('button', { name: t('Вставить в конец', 'Insert at end'), exact: true })).toBeDisabled();
  expect(errors).toEqual([]);
});
